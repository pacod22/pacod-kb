-- Knowledge Base PostgreSQL initialization
--
-- platform/postgres/kb-db.sh applies this to the database kb at every start of
-- pacod-db-init, as the role kb. It pre-creates the tables and indexes used by
-- the optional database-backed DocumentStore. The pipeline still calls
-- SQLAlchemy Base.metadata.create_all() on startup, so this script is
-- idempotent and acts as a fast, explicit bootstrap.

CREATE TABLE IF NOT EXISTS kb_documents (
    doc_id VARCHAR(64) PRIMARY KEY,
    title VARCHAR(512) NOT NULL,
    source_file VARCHAR(512) NOT NULL,
    source_uri TEXT NOT NULL,
    source_version VARCHAR(255),
    source_sha256 VARCHAR(64) NOT NULL,
    retrieved_at VARCHAR(40) NOT NULL,
    converted_at VARCHAR(40) NOT NULL,
    converter VARCHAR(255) NOT NULL,
    extraction_method VARCHAR(32) NOT NULL,
    language VARCHAR(8) NOT NULL,
    doc_type VARCHAR(64) NOT NULL,
    supersedes VARCHAR(64),
    valid_until VARCHAR(20),
    status VARCHAR(16) NOT NULL DEFAULT 'ok',
    error TEXT,
    chunk_count INTEGER NOT NULL DEFAULT 0,
    body TEXT NOT NULL,
    source_bytes BYTEA,
    source_ext VARCHAR(16)
);

CREATE INDEX IF NOT EXISTS ix_kb_documents_source_sha256
    ON kb_documents (source_sha256);

-- Added after the first release (the pipeline back-fills them too, at start).
ALTER TABLE kb_documents ADD COLUMN IF NOT EXISTS project VARCHAR(64);
ALTER TABLE kb_documents ADD COLUMN IF NOT EXISTS extra TEXT;

CREATE INDEX IF NOT EXISTS ix_kb_documents_project
    ON kb_documents (project);

CREATE TABLE IF NOT EXISTS kb_document_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id VARCHAR(64) NOT NULL REFERENCES kb_documents (doc_id) ON DELETE CASCADE,
    event VARCHAR(64) NOT NULL,
    at VARCHAR(40) NOT NULL,
    detail TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS ix_kb_document_events_doc_id
    ON kb_document_events (doc_id);

