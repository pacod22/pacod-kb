Tone = Literal["good", "bad", "warn", "info", "neutral"]

_NOTICE_ICONS: dict[str, str] = {
    "good": "circle-check",
    "bad": "circle-alert",
    "warn": "triangle-alert",
    "info": "info",
    "neutral": "info",
}


def icon(name: str, size: int = 16, label: str = "") -> Markup:
    """An inline Lucide icon; decorative (``aria-hidden``) unless it has a ``label``."""
    body = _ICONS[name]
    a11y = f'role="img" aria-label="{escape(label)}"' if label else 'aria-hidden="true"'
    return Markup(
        f'<svg class="icon" xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round" {a11y}>{body}</svg>'
    )


def notice(tone: Tone, html: str | Markup) -> Markup:
    """A notice box. ``html`` is inserted as is: escape every value interpolated into it."""
    role = "alert" if tone == "bad" else "status"
    return Markup(
        f'<div class="notice {tone}" role="{role}">{icon(_NOTICE_ICONS[tone])}'
        f'<div class="notice-text">{html}</div></div>'
    )
